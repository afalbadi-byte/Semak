// نطاق صفحات بالتسميات: «٥٨٢–٥٨٦ (النبأ، النازعات)»
export function rangeLabel(list) {
    if (!list || !list.length) return '—';
    const s = [...list].sort((a, b) => a - b);
    const groups = [];
    let a = s[0], b = s[0];
    for (let i = 1; i < s.length; i++) { if (s[i] === b + 1) b = s[i]; else { groups.push([a, b]); a = b = s[i]; } }
    groups.push([a, b]);
    // عزلٌ باتجاه اليسار، فيُقرأ النطاق «٥٨٢–٥٩١» لا «٥٩١–٥٨٢» داخل النص العربي
    return groups.map(([x, y]) => (x === y ? String(x) : '⁦' + x + '–' + y + '⁩')).join('، ');
}
export function surahsIn(list) {
    const seen = [];
    [...(list || [])].sort((a, b) => a - b).forEach(p => surahsOn(p).forEach(n => { if (!seen.includes(n)) seen.push(n); }));
    return seen;
}

// نقطة البداية بأسطر النصّ، والحفظ بالسورة: من الناس صعوداً سورةً سورة (كل سورةٍ من
// أوّلها)، أو من الفاتحة بترتيب المصحف. «أجزاء» و«صفحة» لمن يحفظ من الناس: السور التي
// تبدأ في ذلك الموضع وما بعده، فلا تُحسب سورةٌ ناقصة.
const sum = a => a.reduce((x, y) => x + y, 0);
export function initLinesFor(dir, mode, value) {
    const v = Number(value) || 0;
    if (mode === 'none' || !v) return 0;
    const fromPage = p => sum(SURAH_LINES.filter((n, i) => SURAHS[i][1] >= p));   // سورٌ تبدأ من الصفحة p فما بعدها
    if (mode === 'juz') {
        const n = Math.min(30, v);
        if (dir === 'desc') return fromPage(JUZ_START[30 - n]);
        return sum(PAGE_LINES.slice(0, n < 30 ? JUZ_START[n] - 1 : PAGES));
    }
    if (mode === 'surah') {
        const i = Math.min(114, v) - 1;
        return dir === 'desc' ? sum(SURAH_LINES.slice(i)) : sum(SURAH_LINES.slice(0, i + 1));
    }
    if (mode === 'page') {
        const p = Math.min(PAGES, Math.max(1, v));
        return dir === 'desc' ? fromPage(p) : sum(PAGE_LINES.slice(0, p));
    }
    return 0;
}

