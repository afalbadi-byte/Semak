// السور التي تظهر في الصفحة: التي تبدأ فيها، والتي بدأت قبلها وتستمر إليها
export function surahsOn(p) {
    // تقريبٌ بمستوى الصفحة: السورة تمتدّ من صفحة بدايتها إلى ما قبل بداية التي تليها
    const out = [];
    for (let i = 0; i < SURAHS.length; i++) {
        const start = SURAHS[i][1];
        const next = i + 1 < SURAHS.length ? SURAHS[i + 1][1] : PAGES + 1;
        const end = Math.max(start, next - 1);
        if (p >= start && p <= end) out.push(SURAHS[i][0]);
    }
    return out;
}

