// الأسطر بلغةٍ مفهومة: «٧ أسطر (نصف صفحة تقريباً)»
export function linesLabel(n) {
    n = Number(n) || 0;
    if (!n) return 'لا شيء';
    const pages = Math.floor(n / LPP), rest = n % LPP;
    const parts = [];
    if (pages) parts.push(pages === 1 ? 'صفحة' : pages === 2 ? 'صفحتان' : pages + ' صفحات');
    if (rest) parts.push(rest === 1 ? 'سطر' : rest === 2 ? 'سطران' : rest + (rest <= 10 ? ' أسطر' : ' سطراً'));
    return parts.join(' و');
}

