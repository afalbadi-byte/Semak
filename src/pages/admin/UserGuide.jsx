export default function UserGuide() {
  const [q, setQ] = useState('');

  const filtered = useMemo(() => {
    const t = q.trim();
    if (!t) return GUIDE;
    return GUIDE.map(d => ({
      ...d,
      tools: d.tools.filter(x => x.name.includes(t) || x.what.includes(t) || x.steps.some(s => s.includes(t)) || (x.tips || '').includes(t)),
    })).filter(d => d.tools.length);
  }, [q]);

  return (
    <div className="p-6 md:p-8" dir="rtl">
      <div className="flex items-center justify-between flex-wrap gap-4 mb-6">
        <div>
          <h2 className="text-2xl font-extrabold text-slate-800 dark:text-brand-100 flex items-center gap-2">
            <BookOpen className="w-7 h-7 text-emerald-600" /> دليل الاستخدام
          </h2>
          <p className="text-slate-500 dark:text-brand-300 text-sm mt-1">مرجع تشغيل كل أدوات النظام — اضغط أي أداة لعرض خطوات استخدامها</p>
        </div>
        <div className="relative">
          <Search className="w-4 h-4 text-slate-400 absolute right-3 top-1/2 -translate-y-1/2" />
          <input value={q} onChange={e => setQ(e.target.value)} placeholder="ابحث عن أداة أو خطوة…"
            className="w-72 max-w-full bg-white dark:bg-brand-900 border border-slate-200 dark:border-brand-700 rounded-xl pr-9 pl-4 py-2.5 text-sm outline-none focus:ring-2 focus:ring-emerald-300 dark:text-brand-100" />
        </div>
      </div>

      {filtered.length === 0 ? (
        <p className="text-center text-slate-400 py-16">لا توجد نتائج لـ «{q}»</p>
      ) : filtered.map((d, i) => (
        <section key={i} className="mb-8">
          <h3 className={`flex items-center gap-2 font-black text-${d.color}-700 dark:text-${d.color}-400 mb-3 text-lg`}>
            <d.icon className="w-5 h-5" /> {d.dept}
            <span className="text-xs font-bold text-slate-400 dark:text-brand-400">({d.tools.length} {d.tools.length > 2 ? 'أدوات' : 'أداة'})</span>
          </h3>
          <div className="grid grid-cols-1 xl:grid-cols-2 gap-3">
            {d.tools.map((tool, j) => <ToolCard key={j} tool={tool} />)}
          </div>
        </section>
      ))}

      <p className="text-center text-xs text-slate-400 dark:text-brand-500 mt-10">
        الدليل يتحدث تلقائياً مع كل أداة جديدة تُضاف للنظام · سماك العقارية
      </p>
    </div>
  );
}
