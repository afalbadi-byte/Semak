function ToolCard({ tool }) {
  const [open, setOpen] = useState(false);
  return (
    <div className="bg-white dark:bg-brand-900 rounded-2xl border border-slate-200 dark:border-brand-700 overflow-hidden">
      <button onClick={() => setOpen(o => !o)} className="w-full flex items-center justify-between px-5 py-4 text-right hover:bg-slate-50 dark:hover:bg-brand-800/50 transition">
        <div>
          <h4 className="font-extrabold text-slate-800 dark:text-brand-100">{tool.name}</h4>
          <p className="text-sm text-slate-500 dark:text-brand-300 mt-0.5 leading-relaxed">{tool.what}</p>
        </div>
        {open ? <ChevronUp className="w-5 h-5 text-slate-400 shrink-0 mr-3" /> : <ChevronDown className="w-5 h-5 text-slate-400 shrink-0 mr-3" />}
      </button>
      {open && (
        <div className="px-5 pb-5 border-t border-slate-100 dark:border-brand-800 pt-4">
          <p className="text-xs font-black text-slate-400 dark:text-brand-400 mb-2">خطوات الاستخدام</p>
          <ol className="space-y-2">
            {tool.steps.map((s, i) => (
              <li key={i} className="flex items-start gap-2.5 text-sm text-slate-700 dark:text-brand-200">
                <span className="w-5 h-5 rounded-full bg-emerald-100 dark:bg-emerald-900/50 text-emerald-700 dark:text-emerald-300 text-[11px] font-black flex items-center justify-center shrink-0 mt-0.5">{i + 1}</span>
                <span className="leading-relaxed">{s}</span>
              </li>
            ))}
          </ol>
          {tool.tips && (
            <div className="mt-4 flex items-start gap-2 bg-amber-50 dark:bg-amber-900/20 border border-amber-200 dark:border-amber-800 rounded-xl px-4 py-3">
              <Lightbulb className="w-4 h-4 text-amber-500 shrink-0 mt-0.5" />
              <p className="text-sm text-amber-800 dark:text-amber-200 leading-relaxed">{tool.tips}</p>
            </div>
          )}
        </div>
      )}
    </div>
  );
}

